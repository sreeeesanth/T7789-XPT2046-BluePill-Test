/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_SPI1_Init();

  /* USER CODE BEGIN 2 */

  /* Turn ON TFT backlight */
  HAL_GPIO_WritePin(TFT_LED_GPIO_Port, TFT_LED_Pin, GPIO_PIN_SET);

  /*
   * Initialize ST7789 TFT
   *
   * Display:
   * ST7789 240x240
   */
  ST7789_Init();

  ST7789_WriteString(
      20,
      20,
      "ST7789 TEST",
      Font_16x26,
      WHITE,
      BLACK
  );

  ST7789_DrawLine(0, 60, 239, 60, RED);
  ST7789_DrawLine(0, 61, 239, 61, RED);

  ST7789_DrawRectangle(20, 80, 140, 160, GREEN);

  ST7789_DrawFilledRectangle(170, 80, 130, 80, WHITE);

  ST7789_DrawCircle(80, 200, 30, YELLOW);

  ST7789_DrawFilledCircle(200, 200, 30, BLUE);

  /*
   * Initialize XPT2046 Touch
   *
   * SPI1
   * Landscape
   * 240x240 display
   */
  XPT2046_init(
      &hspi1,
      XPT2046_LANDSCAPE,
      ST7789_WIDTH,
      ST7789_HEIGHT
  );

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
      if (HAL_GPIO_ReadPin(XPT2046_IRQ_GPIO_Port, XPT2046_IRQ_Pin) == GPIO_PIN_RESET)
      {
          touch = XPT2046_getTouch();

          touch.x = ST7789_WIDTH - 1 - touch.x;

          if (touch.x < ST7789_WIDTH && touch.y < ST7789_HEIGHT)
          {
              ST7789_DrawFilledCircle(touch.x, touch.y, 6, GREEN);
          }
      }

      HAL_Delay(10);
  }
  /* USER CODE END 3 */
}

